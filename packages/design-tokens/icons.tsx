/**
 * The ecosystem's icon set (CONVENTIONS.md design anti-pattern rule 2 requires
 * an adopted set to be a deliberate, documented decision: this is it).
 *
 * First-party, static SVG on a 24px grid with one consistent 2px round
 * stroke in `currentColor`, so icons take their colour from the surrounding
 * text and never animate on hover (rule 28). Decorative by default
 * (aria-hidden); pass `label` when an icon is the only content of a control.
 * Add new glyphs here in the same style rather than importing another set.
 */
import type { ReactNode, SVGProps } from 'react';

export interface IconProps extends Omit<SVGProps<SVGSVGElement>, 'children'> {
  size?: number;
  /** Accessible name; omit for decorative icons. */
  label?: string;
}

function Svg({ size = 16, label, children, ...rest }: IconProps & { children: ReactNode }) {
  return (
    <svg
      width={size}
      height={size}
      viewBox="0 0 24 24"
      fill="none"
      stroke="currentColor"
      strokeWidth={2}
      strokeLinecap="round"
      strokeLinejoin="round"
      role={label ? 'img' : undefined}
      aria-label={label}
      aria-hidden={label ? undefined : true}
      focusable="false"
      {...rest}
    >
      {children}
    </svg>
  );
}

