import type {
  VerificationMethodProvider,
  VerificationContext,
  VerificationResult,
  PendingResult,
} from './types';
import { parseImageCallback, type ImageCallbackPayload } from './image-callback-payload';
import { mockScoreFor } from './mock-outcome';
import { evaluateDocument } from '@nid/ocr-engine';
import { evaluateForensics } from '@nid/forensics-engine';

/**
 * Checks a submitted document against whatever this instance verifies — a
 * government ID (document_ocr), a birth certificate (dob_document), a
 * diploma/transcript (education_document), or an offer letter/paystub
 * (employment_document). One class, one file, instantiated once per
 * ClaimType in registry.ts (docs/HOUSE-RULES.md rule 1) — the mechanism
 * (upload an image, evaluate it) doesn't differ by claim type, only which
 * document is expected and what badge a PASSED result earns.
 *
 * start() has nothing to send — the subject's next step is an upload, not
 * receiving a code — so it returns `pending` immediately; handleCallback()
 * does the real work, driven by bytes the caller (an Activity, reading them
 * back from @nid/storage) passes in.
 *
 * `devMode=true` returns a fast mocked result for tests (real interface,
 * mock result, exactly like otp_sms's OTP_SMS_DEV_MODE). `devMode=false`
 * runs the *real* self-hosted pipeline (`@nid/ocr-engine`): Tesseract OCR,
 * then an ICAO 9303 MRZ checksum check when the document has one. This is
 * genuine evidence for MRZ-bearing documents (a passport, some ID cards) —
 * the check digits were generated by the issuing authority at print time,
 * so a mismatch means tampered-or-misread, not a guess. Documents with no
 * MRZ (diplomas, offer letters, many licenses) have no equivalent
 * authority-issued checksum to validate against, so they land on
 * NEEDS_REVIEW with the extracted text attached rather than a fabricated
 * pass — see evaluateDocument()'s own comment for exactly why.
 *
 * Production mode also runs `@nid/forensics-engine`'s image-forensics check
 * (error-level analysis, EXIF consistency, recapture-artifact detection)
 * alongside the OCR/MRZ check, on every claim type — a forged or
 * screen-recaptured document can still pass MRZ's checksum (the checksum
 * only validates the digits OCR actually read, not whether the pixels
 * behind them were manipulated) or simply has no MRZ to check at all. Its
 * corroborated ('TAMPERED') verdict overrides even a PASSED OCR result to
 * FAILED — real negative evidence beats a clean checksum read off tampered
 * pixels; a single-signal ('SUSPICIOUS') verdict only ever downgrades an
 * otherwise-PASSED result to NEEDS_REVIEW, never fails it outright, and
 * never touches a result OCR already flagged — see
 * evaluateForensics()'s own comment for why single-signal evidence isn't
 * treated as strong enough to fail a case on its own.
 */
export class ImageClaimProvider implements VerificationMethodProvider {
  constructor(
    readonly key: string,
    readonly label: string,
    private readonly devMode: boolean,
  ) {}

  async start(_context: VerificationContext): Promise<VerificationResult | PendingResult> {
    return { pending: true };
  }

  async handleCallback(payload: Record<string, unknown>): Promise<VerificationResult> {
    const parsed = parseImageCallback(payload);
    if (!parsed.ok) {
      return { status: 'FAILED', raw: { reason: parsed.reason }, verified: false };
    }
    return this.evaluate(parsed.value);
  }

  private async evaluate(input: ImageCallbackPayload): Promise<VerificationResult> {
    if (this.devMode) {
      const status = input.mockOutcome ?? 'PASSED';
      return {
        status,
        score: mockScoreFor(status),
        raw: {
          mode: 'dev_mock',
          byteLength: input.imageBytes.byteLength,
          contentType: input.contentType,
        },
        verified: true,
      };
    }

    const [documentResult, forensics] = await Promise.all([
      evaluateDocument(input.imageBytes),
      evaluateForensics(input.imageBytes),
    ]);

    let status = documentResult.status;
    if (forensics.verdict === 'TAMPERED') {
      status = 'FAILED';
    } else if (forensics.verdict === 'SUSPICIOUS' && status === 'PASSED') {
      status = 'NEEDS_REVIEW';
    }

    return {
      status,
      raw: { ...documentResult.raw, forensics: { verdict: forensics.verdict, signals: forensics.signals } },
      verified: true,
    };
  }
}
