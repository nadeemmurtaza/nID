import { extractText, extractMrzCandidateText } from './tesseract-ocr';
import { parseTd3Mrz, looksLikeMrzCandidate } from './mrz';
import { autoCropToMrzBand } from './mrz-crop';

const MIN_READABLE_TEXT_LENGTH = 20;

export interface DocumentEvaluation {
  status: 'PASSED' | 'FAILED' | 'NEEDS_REVIEW';
  raw: Record<string, unknown>;
}

/**
 * The real (non-mocked) document check: OCR the image, then decide honestly
 * based on what was actually found. Split into two steps deliberately —
 * getting text out of an image is real I/O against a real engine, worth
 * proving live with a real image; deciding PASSED/FAILED/NEEDS_REVIEW from
 * that text is pure logic, worth full deterministic unit coverage without
 * needing Tesseract to run at all. See decideFromExtractedText's own
 * comment for what each branch means and why.
 */
export async function evaluateDocument(imageBytes: Buffer): Promise<DocumentEvaluation> {
  const text = await extractText(imageBytes);

  // General English OCR's language model actively fights MRZ accuracy — it
  // has no idea what to do with a long run of a repeated filler character
  // that never occurs in real English, and tends to hallucinate stray
  // punctuation into it. Only worth a second, slower, MRZ-restricted pass
  // once the first pass already suggests one is there. That second pass
  // runs against an auto-cropped MRZ band when one is found (real-world MRZ
  // recognition always crops first — see mrz-crop.ts) rather than the
  // whole page, which stops the photo/header text from diluting the
  // whitelisted pass's signal; a crop miss falls back to the full image
  // rather than failing the check.
  let mrzText: string | undefined;
  let mrzCropApplied = false;
  if (looksLikeMrzCandidate(text)) {
    const crop = await autoCropToMrzBand(imageBytes);
    mrzCropApplied = crop.cropped;
    mrzText = await extractMrzCandidateText(crop.imageBytes);
  }

  const evaluation = decideFromExtractedText(text, mrzText);
  // Debuggability, not a decision input — whether the crop heuristic found
  // a band is worth a reviewer knowing when a checksum still comes back
  // invalid, but it never changes PASSED/FAILED/NEEDS_REVIEW itself.
  return { ...evaluation, raw: { ...evaluation.raw, mrzCropApplied } };
}

/**
 * Pure decision logic, no OCR call — takes whatever text was already
 * extracted and decides:
 *
 *  - a passport MRZ whose checksums all match: PASSED, real evidence — the
 *    check digits were generated by the issuing authority at print time.
 *  - an MRZ whose checksums don't match: FAILED — tampered, forged, or
 *    misread; either way not safe to pass automatically.
 *  - no MRZ, but a readable amount of text: NEEDS_REVIEW. Most documents
 *    (diplomas, offer letters, many ID cards) have no ICAO checksum to
 *    validate against; this codebase has no ML model or registry to
 *    confirm them automatically, so it says so instead of guessing.
 *  - no readable text at all: FAILED — not a document this check can do
 *    anything with.
 */
export function decideFromExtractedText(text: string, mrzCandidateText?: string): DocumentEvaluation {
  const mrz = parseTd3Mrz(mrzCandidateText ?? text) ?? (mrzCandidateText ? parseTd3Mrz(text) : null);

  if (mrz) {
    return {
      status: mrz.checksumValid ? 'PASSED' : 'FAILED',
      raw: {
        engine: 'tesseract+mrz',
        mrz: {
          documentType: mrz.documentType,
          issuingCountry: mrz.issuingCountry,
          documentNumber: mrz.documentNumber,
          nationality: mrz.nationality,
          dateOfBirth: mrz.dateOfBirth,
          expiryDate: mrz.expiryDate,
          checksumValid: mrz.checksumValid,
          failedChecks: mrz.failedChecks,
        },
      },
    };
  }

  const readableLength = text.replace(/\s+/g, ' ').trim().length;
  if (readableLength < MIN_READABLE_TEXT_LENGTH) {
    return {
      status: 'FAILED',
      raw: { engine: 'tesseract', reason: 'no_readable_text', readableLength },
    };
  }

  return {
    status: 'NEEDS_REVIEW',
    raw: {
      engine: 'tesseract',
      reason: 'no_mrz_manual_review_required',
      extractedTextPreview: text.slice(0, 200),
    },
  };
}
